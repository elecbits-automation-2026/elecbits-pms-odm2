import { tbl, tableName, ensureLayout, usingLegacyLayout } from "./tables.js";

/* ─── REAL ROWS, ALONGSIDE THE BLOB ──────────────────────────────────────────
   App.jsx persists the whole workspace as two JSON strings in `pms.workspace`.
   That is
   fine for the app's own reads, but nothing else can ask a question of it: no
   "which projects are overdue", no join to an invoice, no per-row permissions,
   and — because it is one row — no way to hide anything from anyone.

   So every save also mirrors the workspace out to the real tables, one row per
   thing. The blob stays authoritative; this is a one-way mirror:

     App state ──► pms.workspace blob (authoritative, unchanged)
               └─► core.projects, core.orgs, pms.scrum_notes, pms.tasks,
                   pms.meetings + its ideas / decisions / challenges,
                   messages (project chat AND the assistant, one table),
                   project_intel, kpi_log, work_updates, trainings,
                   memory, drive_sync_log      (a queryable copy)

   Nothing reads these rows back yet, which is exactly why it is safe to turn
   on: a failed write is invisible to the app and the next save repairs it.

   Run, in order:
       supabase/projects-into-a-real-table.sql
       supabase/every-table-filled.sql
       supabase/nested-data-into-tables.sql
   Without them each write fails harmlessly and the tables stay empty.

   ── Two shape rules worth knowing ──
   • `app_id` is the app's own short id (`uid()`, 8 chars). It is the upsert
     key on every table, because the app's ids are not uuids and the uuid
     primary keys are generated by Postgres.
   • Columns declared `uuid references profiles(id)` only ever receive a real
     uuid. The seeded roster uses ids like 'u-admin', which would violate the
     foreign key and fail the entire batch, so those travel in the matching
     `*_app_id` text column instead.                                          */

const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const isUuid = (v) => typeof v === "string" && UUID_RE.test(v);
/* Only a real uuid may enter a uuid column. */
const fk = (v) => (isUuid(v) ? v : null);

/* An empty date input is "", which Postgres rejects for a `date` column. */
const date = (v) => (typeof v === "string" && /^\d{4}-\d{2}-\d{2}$/.test(v) ? v : null);
const text = (v) => (v == null || v === "" ? null : String(v));
const at = (v) => text(v) || new Date().toISOString();
const arr = (v) => (Array.isArray(v) ? v : []);
const obj = (v) => (v && typeof v === "object" && !Array.isArray(v) ? v : {});
/* Number(null), Number(""), Number(false) and Number([]) are all 0, so a
   plain Number() check turns "no score" into a real zero. When Claude is
   unreachable the app stores score: null and shows "unscored" — recording 0
   would manufacture a damning performance record out of a backend outage. */
/* Build a real instant from a UTC day + a local clock time. */
const localToIso = (day, hm) => {
  if (!date(day) || !/^\d{2}:\d{2}$/.test(String(hm || ""))) return null;
  const [h, mi] = String(hm).split(":").map(Number);
  const d = new Date(`${day}T00:00:00`);      // local midnight of that day
  d.setHours(h, mi, 0, 0);
  return Number.isNaN(d.getTime()) ? null : d.toISOString();
};
const num = (v) => (v === null || v === undefined || v === "" || typeof v === "boolean" || Array.isArray(v)
  || !Number.isFinite(Number(v)) ? null : Number(v));
/* Integer columns reject 3.5. A model asked for 1-5 sometimes answers 3.5. */
const int = (v) => { const n = num(v); return n === null ? null : Math.round(n); };

