/* ── the mirror ───────────────────────────────────────────────────────────── */

/* PostgREST parses a quoted list element with BACKSLASH escapes, not doubled
   quotes. Getting this wrong is not cosmetic: a value ending in a backslash
   escapes its own closing quote and swallows the rest of the list. */
const quoted = (v) => `"${String(v).replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;

/* What this browser wrote last time, per table. The prune below deletes only
   keys that WE wrote and have since removed — never "everything that is not
   in my copy".

   That distinction is the whole safety story:

   • On the first save after a reload this is empty, so nothing is deleted. A
     boot that silently came up on seed data — which happens when the blob read
     returns no rows rather than an error — can no longer wipe the database.
   • "Reset to seed data" is a local action again, not one that destroys the
     shared mirror for the whole company.
   • Two people with the app open no longer delete each other's rows on every
     save. Each prunes only what it personally removed.
   • The delete filter now lists only the removed keys, not every surviving
     one, so it cannot outgrow the URL length limit at ~1,000 rows.

   The trade is stale rows: a deletion made in another browser is not mirrored
   until this one also sees it. Stale beats destroyed. */
const lastWrote = new Map();

const DELETE_CHUNK = 100;

/* Upsert `rows` into `table`, then delete only the keys this browser wrote
   before and no longer has. Never throws for a reason the caller can ignore. */
async function mirror(sb, table, rows, key) {
  const seen = new Set();
  const unique = rows.filter((r) => {
    const k = r[key];
    if (!k || seen.has(k)) return false;
    seen.add(k);
    return true;
  });

  if (unique.length) {
    const { error } = await tbl(sb, table).upsert(unique, { onConflict: key });
    if (error) throw new Error(`${tableName(table)}: ${error.message}`);
  }

  const before = lastWrote.get(table);
  const gone = before ? [...before].filter((k) => !seen.has(k)) : [];
  for (let i = 0; i < gone.length; i += DELETE_CHUNK) {
    const batch = gone.slice(i, i + DELETE_CHUNK);
    const { error } = await tbl(sb, table).delete()
      .in(key, batch);
    if (error) throw new Error(`${tableName(table)}: ${error.message}`);
  }
  // Only recorded once the writes have actually landed, so a failed save does
  // not make us forget rows we are still responsible for.
  lastWrote.set(table, seen);

  return unique.length;
}

/* Mirror the whole workspace. `state` is the same object the blob is built
   from, plus the pieces nested inside projects.

   Returns { ok, wrote: {table: n}, errors: [] } and never throws — the caller
   is a save path that must not be interrupted by a backend hiccup. A failure
   in one table does not stop the others. */
export async function syncAll(sb, state = {}) {
  // Decide once which layout this database is in; every job then goes there.
  await ensureLayout(sb);
  const out = { ok: true, wrote: {}, errors: [] };
  if (!sb) return { ok: false, wrote: {}, errors: ["no client"] };

  const projects = arr(state.projects).filter((p) => p && String(p.projectId || "").trim());

  // The three collections that live *inside* each project, flattened out so
  // they can be asked about across the whole company. A brainstorming session
  // additionally fans out into its own child rows.
  const moms = [], ideas = [], decisions = [], challenges = [], messages = [], intel = [];
  for (const p of projects) {
    const pid = String(p.projectId).trim();
    for (const m of arr(p.moms)) {
      if (!m?.id) continue;
      moms.push(momRow(m, pid));
      // '<mom>:<seq>' is the child key — see nested-data-into-tables.sql. It is
      // what lets the children use the same upsert-and-prune path as every
      // other table instead of a bespoke one.
      for (const r of momIdeaRows(m))      ideas.push({ app_id: `${m.id}:${r.seq}`, mom_app_id: m.id, ...r });
      for (const r of momDecisionRows(m))  decisions.push({ app_id: `${m.id}:${r.seq}`, mom_app_id: m.id, ...r });
      for (const r of momChallengeRows(m)) challenges.push({ app_id: `${m.id}:${r.seq}`, mom_app_id: m.id, ...r });
    }
    for (const c of arr(p.chat)) messages.push(projectMessageRow(c, pid));
    for (const i of arr(p.intelligence)) intel.push(projectIntelRow(i, pid));
  }
  for (const m of arr(state.assistantLog)) messages.push(assistantMessageRow(m));

  // Logical names, resolved to schema + table by src/lib/tables.js.
  const jobs = [
    ["projects", projects.map(projectRow), "project_id"],
    ["assignments", projects.flatMap(teamRows), "app_id"],
    ["stages", projects.flatMap(stageRows), "app_id"],
    ["orgs", arr(state.clients).map(clientRow), "app_id"],
    ["scrum_notes", arr(state.notes).map(scrumNoteRow), "app_id"],
    ["tasks", arr(state.tasks).map(taskRow), "app_id"],
    // meetings before its children, so the foreign key has something to point at.
    ["meetings", moms, "app_id"],
    ["meeting_ideas", ideas, "app_id"],
    ["meeting_decisions", decisions, "app_id"],
    ["meeting_challenges", challenges, "app_id"],
    ["messages", messages, "app_id"],
    ["intel", intel, "app_id"],
    ["kpi_log", arr(state.kpiLog).map(kpiRow), "app_id"],
    ["work_updates", arr(state.workUpdates).map(workUpdateRow), "app_id"],
    ["trainings", arr(state.trainings).map(trainingRow), "app_id"],
    ["memory", arr(state.memory).map(memoryRow), "app_id"],
    ["sync_log", arr(state.syncLog).map(syncLogRow), "app_id"],
  ];

  for (const [table, rows, key] of jobs) {
    try {
      out.wrote[table] = await mirror(sb, table, rows, key);
    } catch (e) {
      out.ok = false;
      out.errors.push(e?.message || String(e));
    }
  }
  return out;
}

/* Kept for the projects-only path and for tests. */
export async function syncProjects(sb, projects) {
  if (!sb) return { ok: false, wrote: 0, removed: 0, error: "no client" };
  try {
    const wrote = await mirror(sb, "projects", arr(projects)
      .filter((p) => p && String(p.projectId || "").trim())
      .map(projectRow), "project_id");
    return { ok: true, wrote, removed: 0, error: "" };
  } catch (e) {
    return { ok: false, wrote: 0, removed: 0, error: e?.message || String(e) };
  }
}
